    additionalEditorconfig.set(
        mapOf(
            "ktlint_code_style" to "ktlint_official",
            "ktlint_standard_function-expression-body" to "disabled",
        ),
    )
    baseline.set(file("config/ktlint/baseline.xml"))
}

