// detekt runs source-only: no type-resolution classpath, because detekt 1.23.x bundles an older
// Kotlin compiler than the project uses. detekt-baseline.xml grandfathers the findings inherited
// from upstream so only new code gates; regenerate it with `./gradlew detektBaseline` only when
// an inherited finding is deliberately fixed.
detekt {
    config.setFrom(files("detekt.yml"))
    buildUponDefaultConfig = true
    baseline = file("detekt-baseline.xml")
}

tasks.withType<Detekt>().configureEach {
    exclude("**/build/**")
}

// ktlint uses the official code style plus .editorconfig. Inherited violations live in
// config/ktlint/baseline.xml (`./gradlew ktlintGenerateBaseline`); never run a tree-wide ktlintFormat.
